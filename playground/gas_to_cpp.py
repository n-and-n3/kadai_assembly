#!/usr/bin/env python3
"""Package one or more GAS sources as a single GCC C++ source file."""

import argparse
import sys
from pathlib import Path


def package_sources(paths: list[Path], original_source: str | None = None) -> str:
    # Keep each file's contents intact; a missing final newline must not merge
    # the last directive of one file with the first directive of the next.
    source = "".join(
        data if data.endswith("\n") else data + "\n"
        for data in (path.read_text(encoding="utf-8") for path in paths)
    )

    # A C++ raw-string delimiter may have at most 16 characters. Select one
    # that does not occur as a closing sequence in the assembly source.
    for index in range(10000):
        delimiter = f"GAS{index}"
        if f'){delimiter}"' not in source:
            break
    else:
        raise ValueError("could not find a free C++ raw-string delimiter")

    result = "// Generated by gas_to_cpp.py; submit as GCC C++.\n"
    if original_source is not None:
        result += "// Original source:\n"
        result += "".join(f"// {line}\n" for line in original_source.splitlines())
        result += "\n"
    result += f'asm(R"{delimiter}(\n{source}){delimiter}");\n'
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sources", nargs="+", type=Path, help="GAS sources in link order")
    parser.add_argument("-o", "--output", type=Path, help="C++ output path; defaults to stdout")
    original = parser.add_mutually_exclusive_group()
    original.add_argument("--source-text", help="original language source to show as comments before assembly")
    original.add_argument("--source-file", type=Path, help="file containing the original language source")
    args = parser.parse_args()

    try:
        original_source = (
            args.source_file.read_text(encoding="utf-8")
            if args.source_file is not None
            else args.source_text
        )
        output = package_sources(args.sources, original_source)
        if args.output is None:
            sys.stdout.write(output)
        else:
            args.output.write_text(output, encoding="utf-8")
    except (OSError, ValueError) as exc:
        parser.exit(1, f"gas_to_cpp.py: {exc}\n")


if __name__ == "__main__":
    main()
